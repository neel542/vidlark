# Page pieces, taken from website/index.html so the header, footer, icons and stylesheet
# version always match the hand-written pages.

class Shell:
    def __init__(self, problems: Problems):
        home = HOME.read_text(encoding="utf-8")
        m = re.search(r'<header class="nav[^"]*">.*?</header>', home, re.S)
        f = re.search(r'<footer class="foot">.*?</footer>', home, re.S)
        v = re.search(r"/assets/site\.css\?v=(\w+)", home)
        j = re.search(r"/assets/site\.js\?v=(\w+)", home)
        if not (m and f and v and j):
            raise SystemExit("website/index.html: cannot find the header, footer or stylesheet link to copy")
        header = re.sub(r'^<header class="nav[^"]*">', '<header class="nav">', m.group(0))
        self.header = re.sub(r'\s+aria-current="[^"]*"', "", header)
        if 'href="/blog"' not in self.header:
            problems.error("website/index.html", "the navigation has no Blog link")
        self.footer = f.group(0)
        self.css = v.group(1)
        self.js = j.group(1)
        symbols = []
        for sid in ("i-check", "i-github", "i-arrow", "i-menu"):
            s = re.search(r'<symbol id="' + sid + r'".*?</symbol>', home, re.S)
            if s:
                symbols.append(s.group(0))
        symbols.append(RSS_SYMBOL)
        self.sprite = ('<svg width="0" height="0" style="position:absolute" aria-hidden="true">\n  <defs>\n'
                       '    <!-- Most icons are from Lucide (lucide.dev), ISC License: /assets/icons-license.txt -->\n    '
                       + "\n    ".join(symbols) + "\n  </defs>\n</svg>")

    def nav(self, current: str) -> str:
        return self.header.replace('<a href="/blog">', f'<a href="/blog" aria-current="{current}">', 1)

    def head(self, *, title, description, canonical, image, image_alt, image_size, theme, og_type="website",
             extra="", data=None) -> str:
        w, h = image_size or (1200, 630)
        parts = [
            '<!doctype html>', '<html lang="en">', '<head>', '<meta charset="utf-8">',
            '<meta name="viewport" content="width=device-width, initial-scale=1">',
            f"<title>{esc(title)}</title>",
            f'<meta name="description" content="{esc(description)}">',
            f'<link rel="canonical" href="{esc(canonical)}">',
            '<meta name="robots" content="index, follow, max-image-preview:large">',
            f'<meta name="theme-color" content="{theme}">',
            '<meta property="og:site_name" content="Vidlark">',
            f'<meta property="og:type" content="{og_type}">',
            f'<meta property="og:title" content="{esc(title)}">',
            f'<meta property="og:description" content="{esc(description)}">',
            f'<meta property="og:url" content="{esc(canonical)}">',
            f'<meta property="og:image" content="{esc(BASE + image)}">',
            f'<meta property="og:image:width" content="{w}">',
            f'<meta property="og:image:height" content="{h}">',
            f'<meta property="og:image:alt" content="{esc(image_alt)}">',
        ]
        if extra:
            parts.append(extra)
        parts += [
            '<meta name="twitter:card" content="summary_large_image">',
            f'<meta name="twitter:title" content="{esc(title)}">',
            f'<meta name="twitter:description" content="{esc(description)}">',
            f'<meta name="twitter:image" content="{esc(BASE + image)}">',
            f'<meta name="twitter:image:alt" content="{esc(image_alt)}">',
            '<link rel="icon" href="/favicon.ico" sizes="32x32">',
            '<link rel="icon" href="/assets/mark.svg" type="image/svg+xml">',
            '<link rel="apple-touch-icon" href="/assets/apple-touch-icon.png">',
            '<link rel="manifest" href="/site.webmanifest">',
            '<link rel="alternate" type="application/rss+xml" title="Vidlark blog" href="/blog/feed.xml">',
            '<link rel="preconnect" href="https://fonts.googleapis.com">',
            '<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>',
            '<link href="https://fonts.googleapis.com/css2?family=Bricolage+Grotesque:opsz,wdth,wght@12..96,75..100,400..800'
            '&family=JetBrains+Mono:wght@400;500&display=swap" rel="stylesheet">',
            f'<link rel="stylesheet" href="/assets/site.css?v={self.css}">',
        ]
        if data:
            parts.append(jsonld(data))
        parts.append("</head>")
        return "\n".join(parts)

    def tail(self) -> str:
        return f"{self.footer}\n\n<script src=\"/assets/site.js?v={self.js}\" defer></script>\n</body>\n</html>\n"


def publisher():
    return {"@type": "Organization", "name": "Vidlark", "url": BASE + "/",
            "logo": {"@type": "ImageObject", "url": LOGO, "width": 512, "height": 512}}


def crumbs_html(items) -> str:
    lis = []
    for name, href in items:
        if href:
            lis.append(f'<li><a href="{esc(href)}">{esc(name)}</a></li>')
        else:
            lis.append(f'<li aria-current="page">{esc(name)}</li>')
    return f'<nav class="crumbs" aria-label="Breadcrumb"><ol>{"".join(lis)}</ol></nav>'


def crumbs_data(items):
    return {"@type": "BreadcrumbList", "itemListElement": [
        {"@type": "ListItem", "position": k + 1, "name": name, "item": BASE + url}
        for k, (name, url) in enumerate(items)]}


def card(post: Post, level: int = 3) -> str:
    size = post.meta.get("cover_size") or (1600, 900)
    d = post.meta["date"]
    mins = max(1, round(post.words / WPM))
    return (
        f'<article class="post-card" data-category="{post.cat_slug}" style="--c:var(--{post.colour})">'
        f'<img src="{esc(post.meta["cover"])}" alt="" width="{size[0]}" height="{size[1]}" loading="lazy" decoding="async">'
        f'<div class="post-card-body">'
        f'<p class="post-cat"><i aria-hidden="true"></i>{esc(post.meta["category"])}</p>'
        f'<h{level}><a href="{post.path_url}">{esc(post.meta["title"])}</a></h{level}>'
        f'<p class="post-card-desc">{esc(post.meta["description"])}</p>'
        f'<p class="post-card-meta"><time datetime="{d.isoformat()}">{short_date(d)}</time> · {mins} min read</p>'
        f"</div></article>"
    )


