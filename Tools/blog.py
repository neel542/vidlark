def render_strip(posts: list[Post]) -> str:
    if not posts:
        return ""
    cards = "\n".join(card(p, 3) for p in posts[:3])
    return ('<section class="band mist" id="from-the-blog" aria-labelledby="from-the-blog-title">\n  <div class="wrap">\n'
            '    <div class="strip-head"><h2 id="from-the-blog-title">From the blog</h2>'
            '<a class="btn ghost" href="/blog">All posts<svg aria-hidden="true"><use href="#i-arrow"/></svg></a></div>\n'
            f'    <div class="post-cards">\n{cards}\n    </div>\n  </div>\n</section>\n')


def rfc822(d: dt.date) -> str:
    days = ["Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun"]
    return f"{days[d.weekday()]}, {d.day:02d} {d.strftime('%b')} {d.year} 00:00:00 +0000"


def render_feed(posts: list[Post]) -> str:
    x = lambda s: html.escape(str(s), quote=False)  # noqa: E731
    newest = max((p.meta["updated"] for p in posts), default=dt.date.today())
    items = []
    for p in posts[:50]:
        cover = local_file(p.meta["cover"])
        enclosure = (f'\n      <enclosure url="{esc(BASE + p.meta["cover"])}" length="{cover.stat().st_size}" '
                     f'type="image/{cover.suffix.lstrip(".").replace("jpg", "jpeg")}"/>' if cover else "")
        items.append(f"""    <item>
      <title>{x(p.meta["title"])}</title>
      <link>{p.url}</link>
      <guid isPermaLink="true">{p.url}</guid>
      <pubDate>{rfc822(p.meta["date"])}</pubDate>
      <category>{x(p.meta["category"])}</category>
      <description>{x(p.meta["description"])}</description>{enclosure}
    </item>""")
    return f"""<?xml version="1.0" encoding="UTF-8"?>
<rss version="2.0" xmlns:atom="http://www.w3.org/2005/Atom">
  <channel>
    <title>Vidlark blog</title>
    <link>{BASE}/blog</link>
    <atom:link href="{BASE}/blog/feed.xml" rel="self" type="application/rss+xml"/>
    <description>{x(BLOG_DESCRIPTION)}</description>
    <language>en</language>
    <lastBuildDate>{rfc822(newest)}</lastBuildDate>
{chr(10).join(items)}
  </channel>
</rss>
"""


def git_date(path: Path):
    """The page's last change: today if it has uncommitted changes, else its last commit's date."""
    rel = str(path.relative_to(ROOT))
    try:
        dirty = subprocess.run(["git", "status", "--porcelain", "--", rel], cwd=ROOT, capture_output=True,
                               text=True, check=True).stdout.strip()
        if dirty:
            return dt.date.today()
        out = subprocess.run(["git", "log", "-1", "--format=%cs", "--", rel], cwd=ROOT, capture_output=True,
                             text=True, check=True).stdout.strip()
        if out:
            return dt.date.fromisoformat(out)
    except (OSError, subprocess.CalledProcessError, ValueError):
        pass
    return dt.date.fromtimestamp(path.stat().st_mtime)


def render_sitemap(posts: list[Post]) -> str:
    rows = []
    newest = max((p.meta["updated"] for p in posts), default=None)
    pages = sorted(SITE.glob("*.html"), key=lambda p: (p.name != "index.html", p.name))
    for page in pages:
        if page.name == "404.html" or 'name="robots" content="noindex' in page.read_text(encoding="utf-8"):
            continue
        loc = "/" if page.name == "index.html" else "/" + page.stem
        last = git_date(page)
        if page.name == "index.html" and newest and newest > last:
            last = newest  # the home page shows the latest posts
        rows.append((loc, last))
    if newest:
        blog_last = newest
    elif (BLOG_OUT / "index.html").exists():
        blog_last = git_date(BLOG_OUT / "index.html")
    else:
        blog_last = dt.date.today()
    rows.append(("/blog", blog_last))
    rows += [(p.path_url, p.meta["updated"]) for p in posts]
    body = "\n".join(f"  <url><loc>{BASE}{loc}</loc><lastmod>{d.isoformat()}</lastmod></url>" for loc, d in rows)
    return ('<?xml version="1.0" encoding="UTF-8"?>\n'
            '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' + body + "\n</urlset>\n")


def update_home_strip(posts: list[Post], problems: Problems) -> bool:
    home = HOME.read_text(encoding="utf-8")
    a, b = home.find(STRIP_START), home.find(STRIP_END)
    if a < 0 or b < a:
        problems.error("website/index.html", "the blog strip markers are missing (<!-- blog:latest:start ... --> "
                                             "and <!-- blog:latest:end -->)")
        return False
    a = home.index("-->", a) + 3
    new = home[:a] + "\n" + render_strip(posts) + home[b:]
    return write(HOME, new)


