# Front matter: the small YAML subset the README describes.

KEY_RE = re.compile(r"^([A-Za-z_][\w-]*):(?:[ \t]+(.*)|[ \t]*)$")


def indent_of(line: str) -> int:
    return len(line) - len(line.lstrip(" "))


def parse_scalar(raw: str):
    raw = raw.strip()
    if raw in (">", "|", ">-", "|-"):
        return ""
    if raw.startswith(('>', '|')) and raw[:2] in ("> ", "| "):
        raw = raw[2:].strip()
    if not raw:
        return ""
    if raw[0] == '"':
        if not raw.endswith('"') or len(raw) < 2:
            raise ValueError(f"a quoted value is not closed: {raw[:40]}")
        try:
            return json.loads(raw)
        except json.JSONDecodeError:
            return raw[1:-1]
    if raw[0] == "'":
        if not raw.endswith("'") or len(raw) < 2:
            raise ValueError(f"a quoted value is not closed: {raw[:40]}")
        return raw[1:-1].replace("''", "'")
    if raw.startswith("[") and raw.endswith("]"):
        inner = raw[1:-1].strip()
        if not inner:
            return []
        parts, cur, quote = [], "", None
        for ch in inner:
            if quote:
                cur += ch
                if ch == quote:
                    quote = None
            elif ch in "\"'":
                quote = ch
                cur += ch
            elif ch == ",":
                parts.append(cur)
                cur = ""
            else:
                cur += ch
        parts.append(cur)
        return [parse_scalar(p) for p in parts if p.strip()]
    raw = re.split(r"\s+#", raw, maxsplit=1)[0].strip()  # a comment after a plain value
    if raw in ("true", "false"):
        return raw == "true"
    return raw


def parse_front_matter(src: str):
    lines = src.split("\n")
    data = {}
    i = 0
    while i < len(lines):
        line = lines[i]
        if not line.strip() or line.lstrip().startswith("#"):
            i += 1
            continue
        if indent_of(line) != 0:
            raise ValueError(f"front matter line {i + 2} is indented but belongs to nothing: {line.strip()[:50]}")
        m = KEY_RE.match(line)
        if not m:
            raise ValueError(f"front matter line {i + 2} is not 'key: value': {line.strip()[:50]}")
        key, rest = m.group(1), (m.group(2) or "").strip()
        i += 1
        block = []
        while i < len(lines) and (not lines[i].strip() or indent_of(lines[i]) > 0):
            block.append(lines[i])
            i += 1
        while block and not block[-1].strip():
            block.pop()
        if rest and rest not in (">", "|", ">-", "|-"):
            data[key] = parse_scalar(" ".join([rest] + [b.strip() for b in block if b.strip()]))
        elif block and block[0].strip().startswith("-"):
            data[key] = parse_list(block)
        else:
            data[key] = " ".join(b.strip() for b in block if b.strip())
    return data


def parse_list(block: list[str]):
    items = []
    cur = None  # ["scalar", [parts]] or ["map", {key: [parts]}, last_key, item_indent]
    for line in block:
        if not line.strip():
            continue
        s = line.strip()
        ind = indent_of(line)
        if s == "-" or s.startswith("- "):
            content = s[1:].strip()
            m = KEY_RE.match(content)
            if m and not content.startswith(("'", '"')):
                cur = ["map", {m.group(1): [m.group(2) or ""]}, m.group(1), ind]
            else:
                cur = ["scalar", [content]]
            items.append(cur)
            continue
        if cur is None:
            raise ValueError(f"a list item must start with '- ': {s[:50]}")
        if cur[0] == "map":
            m = KEY_RE.match(s)
            if m and ind <= cur[3] + 2:
                cur[1][m.group(1)] = [m.group(2) or ""]
                cur[2] = m.group(1)
                continue
            cur[1][cur[2]].append(s)
        else:
            cur[1].append(s)
    out = []
    for item in items:
        if item[0] == "map":
            out.append({k: parse_scalar(" ".join(p for p in v if p.strip() not in (">", "|", ">-", "|-")))
                        for k, v in item[1].items()})
        else:
            out.append(parse_scalar(" ".join(item[1])))
    return out


