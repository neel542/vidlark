# Markdown: a small, careful converter for the subset posts use. Every piece of text is
# HTML-escaped; raw HTML in a post is shown as text, never passed through.

LIST_RE = re.compile(r"^( {0,12})([-*+]|\d{1,9}[.)])( +|$)(.*)$")
FENCE_RE = re.compile(r"^( {0,3})(`{3,}|~{3,})[ \t]*([\w+#.-]*)[ \t]*$")
HEADING_RE = re.compile(r"^ {0,3}(#{1,6})[ \t]+(.*?)[ \t]*#*[ \t]*$")
HR_RE = re.compile(r"^ {0,3}((\*[ \t]*){3,}|(-[ \t]*){3,}|(_[ \t]*){3,})$")
IMAGE_LINE_RE = re.compile(r'^!\[([^\]]*)\]\(\s*<?([^)\s>]+)>?(?:\s+"([^"]*)")?\s*\)$')
SAFE_SCHEMES = ("http://", "https://", "mailto:")


def slugify(text: str) -> str:
    text = re.sub(r"<[^>]+>", "", text)
    text = html.unescape(text).lower()
    text = re.sub(r"[^\w\s-]", "", text)
    text = re.sub(r"[\s_]+", "-", text).strip("-")
    return re.sub(r"-{2,}", "-", text) or "section"


def strip_md(text: str) -> str:
    """Markdown inline syntax to plain text (for JSON-LD and the table of contents)."""
    text = re.sub(r"!\[([^\]]*)\]\([^)]*\)", r"\1", text)
    text = re.sub(r"\[([^\]]+)\]\([^)]*\)", r"\1", text)
    text = re.sub(r"<(https?://[^>]+)>", r"\1", text)
    text = re.sub(r"(\*\*|__|~~)(.+?)\1", r"\2", text)
    text = re.sub(r"(?<!\w)[*_](\S.*?\S|\S)[*_](?!\w)", r"\1", text)
    text = re.sub(r"`+([^`]+)`+", r"\1", text)
    text = re.sub(r"\\([\\`*_{}\[\]()#+\-.!|<>~])", r"\1", text)
    return text.strip()


def is_table_sep(line: str) -> bool:
    if "-" not in line or "|" not in line:
        return False
    cells = split_row(line)
    return bool(cells) and all(re.match(r"^:?-+:?$", c) for c in cells)


def split_row(line: str):
    s = line.strip()
    if s.startswith("|"):
        s = s[1:]
    if s.endswith("|") and not s.endswith("\\|"):
        s = s[:-1]
    return [c.strip().replace("\\|", "|") for c in re.split(r"(?<!\\)\|", s)]


class Markdown:
    def __init__(self, where: str, problems: Problems):
        self.where = where
        self.problems = problems
        self.headings: list[tuple[int, str, str]] = []  # (level, id, plain text)
        self.ids: set[str] = set()
        self.links: list[str] = []
        self.images: list[str] = []
        self._store: list[str] = []

    # ---- blocks

    def convert(self, text: str) -> str:
        lines = text.replace("\r\n", "\n").replace("\t", "    ").split("\n")
        return self.blocks(lines)

    def blocks(self, lines: list[str], tight: bool = False) -> str:
        out: list[str] = []
        para: list[str] = []
        n = len(lines)
        i = 0

        def flush():
            if para:
                text = self.inline(" ".join(p.strip() for p in para))
                out.append(text if tight else f"<p>{text}</p>")
                para.clear()

        while i < n:
            line = lines[i]
            s = line.strip()
            if not s:
                flush()
                i += 1
                continue

            m = FENCE_RE.match(line)
            if m:
                flush()
                fence, lang, ind = m.group(2), m.group(3), len(m.group(1))
                close = re.compile(r"^ {0,3}" + re.escape(fence[0]) + "{" + str(len(fence)) + r",}[ \t]*$")
                i += 1
                code = []
                while i < n and not close.match(lines[i]):
                    code.append(lines[i][ind:] if lines[i][:ind].strip() == "" else lines[i].lstrip())
                    i += 1
                if i >= n:
                    self.problems.warn(self.where, "a code block is not closed with ```")
                i += 1
                cls = f' class="language-{esc(lang.lower())}"' if lang else ""
                out.append(f'<pre class="code"><code{cls}>{esc(chr(10).join(code))}</code></pre>')
                continue

            m = HEADING_RE.match(line)
            if m:
                flush()
                level = len(m.group(1))
                if level == 1:
                    self.problems.warn(self.where, "'# ' in the body is shown as '## ': the title is the page's only h1")
                    level = 2
                level = min(level, 4)
                inner = self.inline(m.group(2))
                plain = strip_md(m.group(2))
                hid = slugify(plain)
                base, k = hid, 2
                while hid in self.ids:
                    hid = f"{base}-{k}"
                    k += 1
                self.ids.add(hid)
                self.headings.append((level, hid, plain))
                out.append(f'<h{level} id="{hid}">{inner}</h{level}>')
                i += 1
                continue

            if HR_RE.match(line):
                flush()
                out.append("<hr>")
                i += 1
                continue

            if s.startswith(">"):
                flush()
                quote = []
                while i < n and lines[i].strip().startswith(">"):
                    q = lines[i].strip()[1:]
                    quote.append(q[1:] if q.startswith(" ") else q)
                    i += 1
                out.append(f'<blockquote class="note">\n{self.blocks(quote)}\n</blockquote>')
                continue

            if "|" in s and i + 1 < n and is_table_sep(lines[i + 1]):
                flush()
                head = split_row(line)
                aligns = []
                for c in split_row(lines[i + 1]):
                    aligns.append("center" if c.startswith(":") and c.endswith(":") else
                                  "right" if c.endswith(":") else "left" if c.startswith(":") else "")
                i += 2
                rows = []
                while i < n and lines[i].strip() and "|" in lines[i]:
                    rows.append(split_row(lines[i]))
                    i += 1

                def cell(tag, text, col):
                    a = aligns[col] if col < len(aligns) else ""
                    style = f' style="text-align:{a}"' if a and a != "left" else ""
                    return f"<{tag}{style}>{self.inline(text)}</{tag}>"

                thead = "".join(cell("th", c, k) for k, c in enumerate(head))
                body = "\n".join("<tr>" + "".join(cell("td", r[k] if k < len(r) else "", k)
                                                  for k in range(len(head))) + "</tr>" for r in rows)
                out.append(f'<div class="table-wrap"><table class="table">\n<thead><tr>{thead}</tr></thead>\n'
                           f'<tbody>\n{body}\n</tbody>\n</table></div>')
                continue

            lm = LIST_RE.match(line)
            if lm and (lm.group(4).strip() or not para):
                flush()
                html_list, i = self.parse_list(lines, i)
                out.append(html_list)
                continue

            m = IMAGE_LINE_RE.match(s)
            if m and not para and (i + 1 >= n or not lines[i + 1].strip()):
                flush()
                out.append(self.figure(m.group(1), m.group(2), m.group(3)))
                i += 1
                continue

            para.append(line)
            i += 1
        flush()
        return "\n".join(out)

    def parse_list(self, lines: list[str], i: int):
        n = len(lines)
        first = LIST_RE.match(lines[i])
        base = len(first.group(1))
        ordered = first.group(2)[0].isdigit()
        start = int(first.group(2)[:-1]) if ordered else 1
        items: list[list[str]] = []
        loose = False

        def sibling(line):
            m = LIST_RE.match(line)
            return m and len(m.group(1)) == base and m.group(2)[0].isdigit() == ordered

        while i < n and sibling(lines[i]):
            m = LIST_RE.match(lines[i])
            content_indent = len(m.group(1)) + len(m.group(2)) + max(1, len(m.group(3)))
            item = [m.group(4)]
            i += 1
            while i < n:
                line = lines[i]
                if not line.strip():
                    j = i
                    while j < n and not lines[j].strip():
                        j += 1
                    if j < n and indent_of(lines[j]) >= content_indent:
                        item.extend([""] * (j - i))
                        i = j
                        continue
                    break
                ind = indent_of(line)
                m2 = LIST_RE.match(line)
                if m2 and ind <= base:
                    break
                if ind >= content_indent or (m2 and ind > base):
                    item.append(line[min(ind, content_indent):])
                    i += 1
                    continue
                s = line.strip()
                if s.startswith(("#", "```", "~~~", ">", "|")):
                    break
                item.append(s)  # a lazy continuation of the item's text
                i += 1
            if "" in item:
                loose = True
            items.append(item)
            j = i
            while j < n and not lines[j].strip():
                j += 1
            if j > i and j < n and sibling(lines[j]):
                loose = True
                i = j
            elif j > i:
                break
        tag = "ol" if ordered else "ul"
        attrs = f' start="{start}"' if ordered and start != 1 else ""
        body = "\n".join(f"<li>{self.blocks(item, tight=not loose)}</li>" for item in items)
        return f"<{tag}{attrs}>\n{body}\n</{tag}>", i

    def figure(self, alt: str, src: str, caption) -> str:
        img = self.img(alt, src, lazy=True)
        tall = ""
        f = local_file(src)
        size = image_size(f) if f else None
        if size and size[1] > size[0]:
            tall = " tall"
        cap = f"<figcaption>{self.inline(caption)}</figcaption>" if caption else ""
        return f'<figure class="post-fig"><div class="shot{tall}">{img}</div>{cap}</figure>'

    def img(self, alt: str, src: str, lazy=True) -> str:
        alt = strip_md(alt)
        if not alt.strip():
            self.problems.error(self.where, f"the image {src} has no alt text: write ![what it shows]({src})")
        url = self.safe_url(src)
        self.images.append(src)
        dims = ""
        f = local_file(src)
        if src.startswith("/"):
            if not f:
                self.problems.error(self.where, f"the image {src} is not in website/")
            else:
                size = image_size(f)
                if size:
                    dims = f' width="{size[0]}" height="{size[1]}"'
        loading = ' loading="lazy" decoding="async"' if lazy else ""
        return f'<img src="{esc(url)}" alt="{esc(alt)}"{dims}{loading}>'

    def safe_url(self, url: str) -> str:
        u = url.strip()
        low = u.lower()
        if ":" in low.split("/")[0] and not low.startswith(SAFE_SCHEMES):
            self.problems.error(self.where, f"the link {u} uses a scheme that is not allowed")
            return "#"
        return u

    # ---- inline

    def _keep(self, rendered: str) -> str:
        self._store.append(rendered)
        return f"\x00{len(self._store) - 1}\x00"

    def inline(self, text: str) -> str:
        text = re.sub(r"(`+)(.+?)\1", lambda m: self._keep(f"<code>{esc(m.group(2).strip())}</code>"), text)
        text = re.sub(r"\\([\\`*_{}\[\]()#+\-.!|<>~])", lambda m: self._keep(esc(m.group(1))), text)
        text = re.sub(r"<(https?://[^\s>]+)>",
                      lambda m: self._keep(self.link(m.group(1), esc(m.group(1)), None)), text)
        text = re.sub(r'!\[([^\]]*)\]\(\s*<?([^)\s>]+)>?(?:\s+"([^"]*)")?\s*\)',
                      lambda m: self._keep(self.img(m.group(1), m.group(2))), text)
        text = re.sub(r'\[([^\]]+)\]\(\s*<?([^)\s>]+)>?(?:\s+"([^"]*)")?\s*\)',
                      lambda m: self._keep(self.link(m.group(2), self.emphasis(esc(m.group(1))), m.group(3))), text)
        text = self.emphasis(esc(text))
        while "\x00" in text:
            text = re.sub(r"\x00(\d+)\x00", lambda m: self._store[int(m.group(1))], text)
        return text

    @staticmethod
    def emphasis(text: str) -> str:
        text = re.sub(r"\*\*(?=\S)(.+?)(?<=\S)\*\*", r"<strong>\1</strong>", text)
        text = re.sub(r"(?<!\w)__(?=\S)(.+?)(?<=\S)__(?!\w)", r"<strong>\1</strong>", text)
        text = re.sub(r"~~(?=\S)(.+?)(?<=\S)~~", r"<del>\1</del>", text)
        text = re.sub(r"(?<![\w*])\*(?=[^\s*])(.+?)(?<=[^\s*])\*(?![\w*])", r"<em>\1</em>", text)
        text = re.sub(r"(?<![\w_])_(?=[^\s_])(.+?)(?<=[^\s_])_(?![\w_])", r"<em>\1</em>", text)
        return text

    def link(self, url: str, label_html: str, title) -> str:
        url = self.safe_url(url)
        self.links.append(url)
        t = f' title="{esc(title)}"' if title else ""
        return f'<a href="{esc(url)}"{t}>{label_html}</a>'


