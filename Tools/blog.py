REQUIRED = ["title", "description", "date", "keyword", "category", "cover", "cover_alt"]


class Post:
    def __init__(self, path: Path):
        self.path = path
        self.slug = path.stem
        self.src = path.name
        self.meta: dict = {}
        self.body = ""
        self.html = ""
        self.headings: list = []
        self.words = 0
        self.faq: list = []
        self.related: list[str] = []
        self.draft = False

    @property
    def url(self):
        return f"{BASE}/blog/{self.slug}"

    @property
    def path_url(self):
        return f"/blog/{self.slug}"

    @property
    def cat_slug(self):
        return CATEGORIES[self.meta["category"]][0]

    @property
    def colour(self):
        return CATEGORIES[self.meta["category"]][1]

    @property
    def social(self):
        """A 1200x630 JPG beside the cover, if Tools/blog_cover.js made one, for link previews."""
        p = local_file(self.social_path)
        return self.social_path if p else None

    @property
    def social_path(self):
        return f"/assets/img/blog/{self.slug}-social.jpg"

    def page_title(self):
        t = self.meta.get("seo_title") or self.meta["title"]
        if "vidlark" not in t.lower() and len(t) + len(" | Vidlark") <= 60:
            t += " | Vidlark"
        return t


def load_post(path: Path, problems: Problems):
    post = Post(path)
    where = f"content/blog/{path.name}"
    text = path.read_text(encoding="utf-8")
    if EM_DASH in text:
        line = text[:text.index(EM_DASH)].count("\n") + 1
        problems.error(where, f"line {line} has an em dash. Use a comma, a colon, a full stop or brackets")
    if not re.match(r"^[a-z0-9]+(-[a-z0-9]+)*$", post.slug):
        problems.error(where, "the file name is the URL: use lowercase letters, numbers and hyphens only")
    elif len(post.slug) > 70:
        problems.warn(where, "the file name (the URL) is long; keep it under 70 characters")
    m = re.match(r"^---[ \t]*\n(.*?)\n---[ \t]*(?:\n|$)", text.replace("\r\n", "\n"), re.S)
    if not m:
        problems.error(where, "the file must start with front matter between two '---' lines")
        return None
    try:
        meta = parse_front_matter(m.group(1))
    except ValueError as e:
        problems.error(where, str(e))
        return None
    post.meta = meta
    post.body = text.replace("\r\n", "\n")[m.end():]
    post.draft = meta.get("draft") is True

    for key in REQUIRED:
        if not isinstance(meta.get(key), str) or not meta.get(key, "").strip():
            problems.error(where, f"'{key}' is missing or empty")
    if any(not isinstance(meta.get(k), str) or not meta.get(k, "").strip() for k in REQUIRED):
        return None
    known = set(REQUIRED) | {"seo_title", "updated", "faq", "related", "draft"}
    for key in meta:
        if key not in known:
            problems.warn(where, f"'{key}' is not a front matter field the generator knows; it is ignored")

    title, desc = meta["title"].strip(), meta["description"].strip()
    if len(title) > 60:
        problems.warn(where, f"title is {len(title)} characters; keep it under 60")
    if meta.get("seo_title") and len(meta["seo_title"]) > 60:
        problems.warn(where, f"seo_title is {len(meta['seo_title'])} characters; keep it under 60")
    if not 140 <= len(desc) <= 160:
        problems.warn(where, f"description is {len(desc)} characters; aim for 140 to 160")

    for key in ("date", "updated"):
        if key in meta:
            try:
                meta[key] = dt.date.fromisoformat(str(meta[key]))
            except ValueError:
                problems.error(where, f"'{key}' must be a date like 2026-10-09")
                return None
    meta.setdefault("updated", meta["date"])
    if meta["updated"] < meta["date"]:
        problems.error(where, "'updated' is before 'date'")
    if meta["date"] > dt.date.today():
        problems.warn(where, f"date {meta['date']} is in the future; the post is still built")

    if meta["category"] not in CATEGORIES:
        problems.error(where, f"category must be one of: {', '.join(CATEGORIES)}")
        return None

    cover = meta["cover"]
    if not cover.startswith("/assets/img/blog/"):
        problems.error(where, "cover must be a path under /assets/img/blog/")
    elif not local_file(cover):
        problems.error(where, f"the cover {cover} is not in website/. Make one with: "
                              f"node Tools/blog_cover.js {post.slug} \"{title}\" \"{meta['category']}\"")
    else:
        size = image_size(local_file(cover))
        meta["cover_size"] = size
        if not size:
            problems.error(where, f"cannot read the size of {cover}; use WebP, JPG or PNG")
        elif size[0] < 1200 or abs(size[0] / size[1] - 16 / 9) > 0.02:
            problems.warn(where, f"the cover is {size[0]}x{size[1]}; it should be 1600x900 (16:9, at least 1200 wide)")
        kb = local_file(cover).stat().st_size // 1024
        if kb > 300:
            problems.warn(where, f"the cover is {kb} KB; keep it under 300 KB")

    faq = meta.get("faq", [])
    if faq:
        if not isinstance(faq, list) or not all(isinstance(x, dict) and str(x.get("q", "")).strip()
                                                and str(x.get("a", "")).strip() for x in faq):
            problems.error(where, "faq must be a list of items, each with q: and a:")
            faq = []
    post.faq = faq
    related = meta.get("related", [])
    if isinstance(related, str):
        related = [related]
    post.related = [str(r).strip() for r in related if str(r).strip()]

    md = Markdown(where, problems)
    post.html = md.convert(post.body)
    for x in faq:  # collect the answers' links, so they are checked too
        md.inline(str(x["q"]))
        md.inline(str(x["a"]))
    post.headings = md.headings
    post.links = md.links
    plain = re.sub(r"```.*?```", " ", post.body, flags=re.S)
    post.words = len(re.findall(r"[A-Za-z0-9][A-Za-z0-9'.,-]*", strip_md(plain)))
    if post.words < 300:
        problems.warn(where, f"the body is {post.words} words; most posts should be longer")

    kw = meta["keyword"].lower()
    if kw not in (title + " " + meta.get("seo_title", "")).lower():
        problems.warn(where, f"the keyword '{meta['keyword']}' is not in the title or seo_title")
    if kw not in desc.lower():
        problems.warn(where, f"the keyword '{meta['keyword']}' is not in the description")
    first = " ".join(strip_md(post.body).split()[:120]).lower()
    if kw not in first:
        problems.warn(where, f"the keyword '{meta['keyword']}' is not in the first 120 words")
    return post


def check_post_links(post: Post, slugs: set, problems: Problems):
    where = f"content/blog/{post.src}"
    for r in post.related:
        if r == post.slug:
            problems.error(where, "related lists the post itself")
        elif r not in slugs:
            problems.error(where, f"related post '{r}' does not exist (content/blog/{r}.md)")
    for url in post.links:
        if url.startswith("#"):
            if url[1:] not in {h[1] for h in post.headings} and url != "#questions":
                problems.error(where, f"the link {url} points to no heading in this post")
            continue
        if url.startswith("/blog/") and url.split("#")[0].split("/")[-1] in slugs:
            continue
        if url.startswith("/") and not local_file(url):
            problems.error(where, f"the link {url} goes to no page on the site")


def related_posts(post: Post, posts: list[Post]) -> list[Post]:
    by_slug = {p.slug: p for p in posts}
    chosen = [by_slug[s] for s in post.related if s in by_slug and s != post.slug]
    for p in posts:  # newest first already
        if len(chosen) >= 3:
            break
        if p is not post and p not in chosen and p.meta["category"] == post.meta["category"]:
            chosen.append(p)
    for p in posts:
        if len(chosen) >= 3:
            break
        if p is not post and p not in chosen:
            chosen.append(p)
    return chosen[:3]


