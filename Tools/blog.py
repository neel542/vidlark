def render_missing_covers(paths: list[Path]):
    for path in paths:
        text = path.read_text(encoding="utf-8")
        m = re.match(r"^---[ \t]*\n(.*?)\n---", text, re.S)
        if not m:
            continue
        try:
            meta = parse_front_matter(m.group(1))
        except ValueError:
            continue
        cover = str(meta.get("cover", ""))
        if cover.startswith("/assets/img/blog/") and not local_file(cover) and meta.get("title"):
            print(f"Rendering a cover for {path.stem}")
            subprocess.run(["node", str(ROOT / "Tools" / "blog_cover.js"), path.stem, str(meta["title"]),
                            str(meta.get("category", "Guides"))], cwd=ROOT, check=False)


def main():
    ap = argparse.ArgumentParser(description="Build the Vidlark blog, the feed and the sitemap, then check the site.")
    ap.add_argument("--check", action="store_true", help="check only; write nothing")
    ap.add_argument("--covers", action="store_true", help="render a cover for any post whose cover file is missing")
    ap.add_argument("--strict", action="store_true", help="treat warnings as errors")
    args = ap.parse_args()

    problems = Problems()
    sources = sorted(p for p in CONTENT.glob("*.md") if p.name.lower() != "readme.md")
    if args.covers and not args.check:
        render_missing_covers(sources)
    loaded = [load_post(p, problems) for p in sources]
    posts = [p for p in loaded if p is not None and not p.draft]
    posts.sort(key=lambda p: (p.meta["date"], p.meta["updated"], p.meta["title"]), reverse=True)
    slugs = {p.slug for p in posts}
    for p in posts:
        check_post_links(p, slugs, problems)

    written = []
    if not args.check and not problems.errors:
        shell = Shell(problems)
        expected = set()
        for p in posts:
            out = BLOG_OUT / f"{p.slug}.html"
            expected.add(out)
            if write(out, render_post(p, posts, shell)):
                written.append(out)
        # Remove pages this script made for posts that are gone or now drafts.
        if BLOG_OUT.exists():
            for old in BLOG_OUT.glob("*.html"):
                if old.name != "index.html" and old not in expected and \
                        "Generated by Tools/blog.py" in old.read_text(encoding="utf-8"):
                    old.unlink()
                    print(f"Removed {old.relative_to(ROOT)} (its post is gone or a draft)")
        for path, text in ((BLOG_OUT / "index.html", render_index(posts, shell)),
                           (BLOG_OUT / "feed.xml", render_feed(posts))):
            if write(path, text):
                written.append(path)
        if update_home_strip(posts, problems):
            written.append(HOME)
        if write(SITE / "sitemap.xml", render_sitemap(posts)):
            written.append(SITE / "sitemap.xml")

    check_site(problems)

    drafts = [p for p in loaded if p is not None and p.draft]
    print(f"{len(posts)} post(s){f', {len(drafts)} draft(s) skipped' if drafts else ''}.")
    if args.check:
        print("Checked only; nothing written.")
    elif problems.errors and not written:
        print("Nothing written: fix the errors below first.")
    else:
        print(f"{len(written)} file(s) changed" + (":" if written else "."))
        for w in written:
            print(f"  {w.relative_to(ROOT)}")
    for w in problems.warnings:
        print(f"WARNING  {w}")
    for e in problems.errors:
        print(f"ERROR    {e}")
    if problems.errors or (args.strict and problems.warnings):
        sys.exit(1)


if __name__ == "__main__":
    main()
