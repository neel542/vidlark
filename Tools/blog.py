# Image sizes (PNG, JPEG, WebP, GIF), so every <img> gets width and height.

def image_size(path: Path):
    try:
        data = path.read_bytes()
    except OSError:
        return None
    if data[:8] == b"\x89PNG\r\n\x1a\n":
        return struct.unpack(">II", data[16:24])
    if data[:6] in (b"GIF87a", b"GIF89a"):
        return struct.unpack("<HH", data[6:10])
    if data[:4] == b"RIFF" and data[8:12] == b"WEBP":
        chunk = data[12:16]
        if chunk == b"VP8X":
            return int.from_bytes(data[24:27], "little") + 1, int.from_bytes(data[27:30], "little") + 1
        if chunk == b"VP8 ":
            w, h = struct.unpack("<HH", data[26:30])
            return w & 0x3FFF, h & 0x3FFF
        if chunk == b"VP8L":
            v = int.from_bytes(data[21:25], "little")
            return (v & 0x3FFF) + 1, ((v >> 14) & 0x3FFF) + 1
        return None
    if data[:2] == b"\xff\xd8":
        i = 2
        while i + 9 < len(data):
            if data[i] != 0xFF:
                i += 1
                continue
            marker = data[i + 1]
            if marker in (0xD8, 0x01, 0xFF) or 0xD0 <= marker <= 0xD7:
                i += 2 if marker != 0xFF else 1
                continue
            length = struct.unpack(">H", data[i + 2:i + 4])[0]
            if 0xC0 <= marker <= 0xCF and marker not in (0xC4, 0xC8, 0xCC):
                h, w = struct.unpack(">HH", data[i + 5:i + 9])
                return w, h
            i += 2 + length
    return None


def local_file(url: str):
    """The file in website/ that a site URL points to, or None. Handles cleanUrls (/how-to)."""
    if url.startswith(BASE):
        url = url[len(BASE):] or "/"
    if not url.startswith("/") or url.startswith("//"):
        return None
    path = url.split("#")[0].split("?")[0]
    if path in ("", "/"):
        return SITE / "index.html"
    rel = path.lstrip("/")
    candidates = [SITE / rel, SITE / (rel + ".html"), SITE / rel / "index.html"]
    for c in candidates:
        if c.is_file():
            return c
    return None


