# Site check: every HTML page in website/

class PageScan(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.lang = None
        self.title = ""
        self.in_title = False
        self.meta = {}
        self.canonical = None
        self.h1 = 0
        self.ids = set()
        self.links = []  # (attr, url)
        self.no_alt = []
        self.jsonld = []
        self._ld = None

    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        if "id" in a:
            self.ids.add(a["id"])
        if tag == "html":
            self.lang = a.get("lang")
        elif tag == "title":
            self.in_title = True
        elif tag == "meta":
            key = a.get("name") or a.get("property")
            if key:
                self.meta[key] = a.get("content", "")
        elif tag == "link":
            if a.get("rel") == "canonical":
                self.canonical = a.get("href")
            if a.get("href"):
                self.links.append(("link", a["href"]))
        elif tag == "h1":
            self.h1 += 1
        elif tag == "a" and a.get("href"):
            self.links.append(("a", a["href"]))
        elif tag in ("img", "script", "source", "video") and (a.get("src") or a.get("poster")):
            if a.get("src"):
                self.links.append((tag, a["src"]))
            if a.get("poster"):
                self.links.append((tag, a["poster"]))
            if tag == "img" and "alt" not in a:
                self.no_alt.append(a.get("src"))
        if tag == "script" and a.get("type") == "application/ld+json":
            self._ld = []

    def handle_endtag(self, tag):
        if tag == "title":
            self.in_title = False
        if tag == "script" and self._ld is not None:
            self.jsonld.append("".join(self._ld))
            self._ld = None

    def handle_data(self, data):
        if self.in_title:
            self.title += data
        if self._ld is not None:
            self._ld.append(data)


def check_site(problems: Problems):
    scans = {}
    pages = sorted(p for p in SITE.rglob("*.html") if "assets" not in p.parts)
    for page in pages:
        text = page.read_text(encoding="utf-8")
        scan = PageScan()
        scan.feed(text)
        scans[page] = (scan, text)
    for page, (scan, text) in scans.items():
        where = str(page.relative_to(ROOT))
        noindex = "noindex" in scan.meta.get("robots", "")
        if EM_DASH in text:
            problems.error(where, f"has {text.count(EM_DASH)} em dash(es)")
        if scan.lang != "en":
            problems.error(where, 'the <html> tag needs lang="en"')
        if scan.h1 != 1:
            problems.error(where, f"has {scan.h1} h1 headings; a page needs exactly one")
        for src in scan.no_alt:
            problems.error(where, f"the image {src} has no alt attribute")
        if len(scan.title) > 60:
            problems.warn(where, f"<title> is {len(scan.title)} characters; keep it under 60")
        desc = scan.meta.get("description", "")
        if not noindex and not 140 <= len(desc) <= 160:
            problems.warn(where, f"meta description is {len(desc)} characters; aim for 140 to 160")
        if not noindex and not scan.canonical:
            problems.error(where, "has no canonical link")
        if not noindex and not scan.meta.get("og:image"):
            problems.error(where, "has no og:image")
        for block in scan.jsonld:
            try:
                json.loads(block)
            except json.JSONDecodeError as e:
                problems.error(where, f"a JSON-LD block does not parse: {e}")
        urls = [u for _, u in scan.links]
        urls += [scan.meta[k] for k in ("og:image", "twitter:image", "og:url") if scan.meta.get(k)]
        if scan.canonical:
            urls.append(scan.canonical)
        for url in urls:
            if url.startswith(("mailto:", "tel:", "javascript:")) or (
                    url.startswith(("http://", "https://")) and not url.startswith(BASE)):
                continue
            if url.startswith("#"):
                target, anchor = page, url[1:]
            else:
                target = local_file(url)
                anchor = url.split("#", 1)[1] if "#" in url else ""
                if target is None:
                    problems.error(where, f"the link {url} goes to no file in website/")
                    continue
            if anchor and target.suffix == ".html":
                ids = scans[target][0].ids if target in scans else set()
                if anchor not in ids:
                    problems.error(where, f"the link {url} points to #{anchor}, which is not on that page")


